import { describe, expect, it } from "vitest";
import { mkdirSync, writeFileSync } from "node:fs";
import corpus from "../data/corpus/ads.json" with { type: "json" };
import { parseApplicability } from "../src/applicability/parse";
import { evaluate } from "../src/applicability/evaluate";
import { summarizeCoverage } from "../src/coverage";
import type { Aircraft } from "../src/domain/aircraft";
import fleetData from "../data/fleet/sample-fleet.json" with { type: "json" };

interface CorpusEntry {
  readonly documentNumber: string;
  readonly applicability: string;
}

const directives = corpus as readonly CorpusEntry[];
const fleet = (fleetData as { aircraft: Aircraft[] }).aircraft;

/**
 * The committed baseline. This is a ratchet, not a target: it exists so that a
 * change to the grammar that quietly parses fewer real directives fails CI
 * instead of passing unnoticed. Raise it when the parser genuinely improves.
 */
const MINIMUM_PARSE_RATE = 0.9;
const MINIMUM_RESOLVED_RATE = 0.5;

describe("parser coverage over the real corpus", () => {
  it("reports how much of the regulation it can and cannot resolve", () => {
    const { total, parsed, fullyResolvable, deferred, deferralsByKind, unparsed } =
      summarizeCoverage(directives);

    const report = [
      "",
      `corpus                 ${total} directives`,
      `parsed                 ${parsed} (${((100 * parsed) / total).toFixed(1)}%)`,
      `fully resolvable       ${fullyResolvable} (${((100 * fullyResolvable) / total).toFixed(1)}%)`,
      `deferred to a document ${deferred}`,
      ...deferralsByKind.map(({ kind, count }) => `  ${kind.padEnd(20)} ${count}`),
      `unparsed               ${unparsed.length}${unparsed.length ? ` (${unparsed.slice(0, 6).join(", ")})` : ""}`,
      "",
    ].join("\n");
    // Written to disk rather than only logged: the README quotes this number,
    // so it has to be a file produced by the test run instead of a claim typed
    // into prose and left to rot.
    mkdirSync("docs", { recursive: true });
    writeFileSync("docs/coverage.md", `# Parser coverage\n\nGenerated by \`npm test\` from \`data/corpus/ads.json\`.\n\n\`\`\`${report}\`\`\`\n`);

    expect(parsed / total).toBeGreaterThanOrEqual(MINIMUM_PARSE_RATE);
    expect((fullyResolvable + deferred) / total).toBeGreaterThanOrEqual(MINIMUM_RESOLVED_RATE);
  });

  it("never claims a model list it did not find in the text", () => {
    // Guards the bug the comment in parse.ts records: an earlier version split
    // the whole clause on commas and produced models such as
    // "787-10 airplanes certificated in any".
    for (const directive of directives) {
      const result = parseApplicability(directive.applicability);
      if (!result.node) continue;
      const models = JSON.stringify(result.node).match(/"models":\[(.*?)\]/g) ?? [];
      for (const group of models) {
        expect(group).not.toMatch(/certificated|airplanes|helicopters|engines/i);
      }
    }
  });
});

describe("fleet evaluation over the real corpus", () => {
  it("settles a manufacturer mismatch definitively instead of deferring", () => {
    // Defect 4. AD 2026-22785 names "Lycoming Engines ... Model engines
    // identified in table 1", so there is no model designation to parse. An
    // earlier version dropped the manufacturer too, leaving only the deferral
    // nodes, so all 400 aircraft came back undetermined. None of them is a
    // Lycoming engine, so the right answer is 400 definite refutations.
    const directive = directives.find((d) => d.documentNumber === "2026-22785");
    expect(directive).toBeDefined();
    const result = parseApplicability(directive!.applicability);
    expect(result.node).not.toBeNull();

    const verdicts = fleet.map((aircraft) => evaluate(result.node!, aircraft).kind);
    expect(verdicts.filter((k) => k === "undetermined")).toHaveLength(0);
    expect(verdicts.filter((k) => k === "does_not_apply")).toHaveLength(fleet.length);
  });

  it("keeps the undetermined share small because a refutation short-circuits", () => {
    // The claim the README makes, asserted rather than assumed: 35% of
    // directives defer to a document, yet far fewer than 35% of decisions are
    // undetermined, because one definite refutation settles a conjunction.
    let undeterminedCount = 0;
    let total = 0;
    for (const directive of directives) {
      const result = parseApplicability(directive.applicability);
      if (!result.node) continue;
      for (const aircraft of fleet) {
        total += 1;
        if (evaluate(result.node, aircraft).kind === "undetermined") undeterminedCount += 1;
      }
    }
    expect(total).toBeGreaterThan(50_000);
    expect(undeterminedCount / total).toBeLessThan(0.05);
  });
});
